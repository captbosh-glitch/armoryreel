#!/usr/bin/env python3
"""Build Armory.Reel from data/*.json into static pages.

    python3 scripts/build.py

Writes index.html plus weapons/, films/, characters/ and categories/ (each with
an index page and one page per entry). Every page it writes carries the
GENERATED marker; a marked page that this build didn't write (an entry was
renamed or removed) is deleted. Edit data/ and the templates here, never the output.

Images are looked up on disk, so a page never points at a missing file:
  weapon art     assets/photos/{art}.jpg, else assets/weapons/{art}.jpg  (art defaults to the slug;
                 no file: the name stands in, and the home page hero skips the weapon)
  gallery        assets/gallery/{photo dir, else gallery.dir, else slug}/{f}
                 Each photo and video belongs to one film ("film", default the weapon's
                 first film): weapon pages filter by it, film pages gather their own.
  posters        assets/posters/{poster}.jpg      (no file: the title block stands in)
  characters     assets/characters/{photo}.jpg    (no file: initials stand in)
A bad cross-reference or a missing gallery file stops the build; images on disk
that no entry uses are listed at the end (except site.json's not_used: images kept on
purpose, like a mislabeled sketch or art a photo has replaced).

Pages show resized copies from assets/thumbs/{width}/ (made here with Pillow, and
remade when the original changes); the weapon page hero and the lightbox use the originals.
The search box reads assets/search-index.json, also written here.
"""
import hashlib, html, json, re, sys
from PIL import Image
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATED = '<!-- generated by scripts/build.py from data/; edit those, not this file -->'
OUTPUT_DIRS = ['weapons', 'films', 'characters', 'categories']


def load(name):
    return json.loads((ROOT / 'data' / f'{name}.json').read_text())


CATS, FILMS, CHARS, WEAPONS, SITE = load('categories'), load('films'), load('characters'), load('weapons'), load('site')
# films list A-Z everywhere, ignoring a leading "The" or "A"
FILMS.sort(key=lambda f: re.sub(r'^(the|a) ', '', re.sub(r'[^a-z0-9 ]', '', f['title'].lower())))
GENRES = load('genres')   # films have a genre; weapons (and living-weapon characters) have a category
CAT = {c['slug']: c for c in CATS}
GENRE = {g['slug']: g for g in GENRES}
FILM = {f['slug']: f for f in FILMS}
CHAR = {c['slug']: c for c in CHARS}
WEAPON = {w['slug']: w for w in WEAPONS}

errors = []
for table, rows in (('categories', CATS), ('films', FILMS), ('characters', CHARS), ('weapons', WEAPONS)):
    seen = set()
    for r in rows:
        if r['slug'] in seen:
            errors.append(f'{table}: duplicate slug {r["slug"]}')
        seen.add(r['slug'])
for f in FILMS:
    if f['genre'] not in GENRE:
        errors.append(f'film {f["slug"]}: unknown genre {f["genre"]}')
for c in CHARS:
    errors += [f'character {c["slug"]}: unknown film {s}' for s in c['films'] if s not in FILM]
    if c.get('category') and c['category'] not in CAT:
        errors.append(f'character {c["slug"]}: unknown category {c["category"]}')
for w in WEAPONS:
    if w['category'] not in CAT:
        errors.append(f'weapon {w["slug"]}: unknown category {w["category"]}')
    errors += [f'weapon {w["slug"]}: unknown film {s}' for s in w['films'] if s not in FILM]
    errors += [f'weapon {w["slug"]}: unknown character {s}' for s in w['carriers'] if s not in CHAR]
errors += [f'site.json: unknown weapon {s}' for s in [SITE['hero_weapon']] + SITE['featured_weapons'] if s not in WEAPON]
errors += [f'site.json: unknown film {s}' for s in SITE['home_films'] if s not in FILM]

used = set()      # every asset a page references, for the unused-image report
written = set()   # every page this build wrote
thumbs_written = set()


def asset(rel):
    """rel (under assets/) if the file exists, else None."""
    if (ROOT / 'assets' / rel).is_file():
        used.add(rel)
        return rel
    return None


def thumb(rel, width):
    """A copy of assets/{rel} at most `width` px wide, in assets/thumbs/{width}/."""
    out = f'thumbs/{width}/{rel}'
    src, dest = ROOT / 'assets' / rel, ROOT / 'assets' / out
    if not dest.exists() or dest.stat().st_mtime < src.stat().st_mtime:
        dest.parent.mkdir(parents=True, exist_ok=True)
        with Image.open(src) as im:
            im = im.convert('RGB')
            if im.width > width:
                im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
            im.save(dest, 'JPEG', quality=82, optimize=True, progressive=True)
    thumbs_written.add(dest)
    return out


def weapon_art(w):
    art = w.get('art', w['slug'])
    return asset(f'photos/{art}.jpg') or asset(f'weapons/{art}.jpg')


def gallery(w):
    g = w.get('gallery') or {}
    folder, first = g.get('dir', w['slug']), w['films'][0]
    photos = []
    for p in g.get('photos', []):
        rel = f'gallery/{p.get("dir", folder)}/{p["f"]}'
        if not asset(rel):
            errors.append(f'weapon {w["slug"]}: missing gallery photo assets/{rel}')
        photos.append(dict(p, rel=rel, film=p.get('film', first), weapon=w['slug']))
    videos = [dict(v, film=v.get('film', first), weapon=w['slug']) for v in g.get('videos', [])]
    errors.extend(f'weapon {w["slug"]}: gallery item {x.get("f") or x["yt"]} is tagged {x["film"]}, not one of its films'
                  for x in photos + videos if x['film'] not in w['films'])
    return photos, videos


def film_gallery(f):
    """Every gallery photo and video tagged with film f, across its weapons (a shared clip once)."""
    photos, videos, seen = [], [], set()
    for w in W_BY_FILM[f]:
        ps, vs = GALLERIES[w['slug']]
        photos += [dict(p, meta=f'{p["meta"]} · {w["name"]}') for p in ps if p['film'] == f and p['rel'] not in seen and not seen.add(p['rel'])]
        videos += [v for v in vs if v['film'] == f and v['yt'] not in seen and not seen.add(v['yt'])]
    return photos, videos


# derived lists
W_BY_FILM = {f: [w for w in WEAPONS if f in w['films']] for f in FILM}
W_BY_CHAR = {c: [w for w in WEAPONS if c in w['carriers']] for c in CHAR}
C_BY_FILM = {f: [c for c in CHARS if f in c['films']] for f in FILM}
GALLERIES = {w['slug']: gallery(w) for w in WEAPONS}
ARTS = {w['slug']: weapon_art(w) for w in WEAPONS}

if errors:
    sys.exit('Build stopped:\n  ' + '\n  '.join(errors))


# ---------- helpers ----------
esc = html.escape


def plural(n, word):
    return f'{n} {word}{"" if n == 1 else "s"}'


def and_list(names):
    return names[0] if len(names) == 1 else ', '.join(names[:-1]) + ' &amp; ' + names[-1]


def media_line(slug):
    photos, videos = GALLERIES[slug]
    return ' · '.join(([plural(len(photos), 'photo')] if photos else []) + ([plural(len(videos), 'video')] if videos else []))


def carriers_line(w):
    people = [CHAR[c] for c in w['carriers']]
    named = [c for c in people if not c.get('note')] or people    # leave groups out when people are named
    return and_list([esc(c['name']) for c in named])


def imdb(path, label, text):
    return (f'<a class="ext" href="https://www.imdb.com/{path}/" target="_blank" rel="noopener" '
            f'aria-label="{esc(label)} on IMDb (opens in a new tab)">{esc(text)}</a>')


def initials(name):
    return ''.join(p[0] for p in name.replace('’', '').split() if p[0].isalnum())[:2].upper()


def poster(f, R, tag='div', href=''):
    rel = asset(f'posters/{f["poster"]}.jpg') if f.get('poster') else None
    img = f'<img src="{R}assets/{thumb(rel, 480)}" alt="" loading="lazy">' if rel else ''
    attr = f' href="{href}"' if href else ''
    return f'<{tag} class="poster"{attr}><span>{esc(f["title"])}</span>{img}</{tag}>'


def char_photo(c, R, tag='div', href=''):
    rel = asset(f'characters/{c["photo"]}.jpg') if c.get('photo') else None
    inner = f'<img src="{R}assets/{thumb(rel, 480)}" alt="" loading="lazy">' if rel else f'<span>{initials(c["name"])}</span>'
    attr = f' href="{href}"' if href else ''
    return f'<{tag} class="photo"{attr}>{inner}</{tag}>'


def art_img(w, width, R, alt=''):
    """The weapon's picture, or its name as a stand-in until the art exists."""
    rel = ARTS[w['slug']]
    if rel:
        return f'<img src="{R}assets/{thumb(rel, width)}" alt="{esc(alt)}" loading="lazy">'
    return f'<span class="stand">{esc(w["name"])}</span>'


def wcard(w, R):
    f = FILM[w['films'][0]]
    media = media_line(w['slug'])
    return (f'<a class="wcard" href="{R}weapons/{w["slug"]}/"><div class="art">{art_img(w, 800, R)}</div>'
            f'<div class="cap"><h3>{esc(w["name"])}</h3>' + (f'<div class="media mono">{media}</div>' if media else '') +
            f'<div class="sub">{esc(f["title"])} · {f["year"]} · <b>{carriers_line(w)}</b></div></div></a>')


def film_card(f, R):
    n = len(W_BY_FILM[f['slug']])
    sub = f'{f["year"]} · ' + (plural(n, 'weapon') if n else 'Coming soon')
    return (f'<a class="film" href="{R}films/{f["slug"]}/">{poster(f, R)}'
            f'<div class="cap"><h3>{esc(f["title"])}</h3><div class="sub">{sub}</div></div></a>')


def char_card(c, R):
    sub = esc(c.get('actor') or c.get('note', ''))
    return (f'<a class="char" href="{R}characters/{c["slug"]}/">{char_photo(c, R)}'
            f'<div class="cap"><h3>{esc(c["name"])}</h3><div class="sub">{sub}</div></div></a>')


def cat_count(c):
    if c.get('counts') == 'characters':
        n = len([x for x in CHARS if x.get('category') == c['slug']])
        return plural(n, 'character') if n else ''
    n = len([w for w in WEAPONS if w['category'] == c['slug']])
    return plural(n, 'weapon') if n else ''


def cat_cards(R):
    out = []
    for i, c in enumerate(CATS, 1):
        n = cat_count(c)
        out.append(f'<a class="cat" href="{R}categories/{c["slug"]}/"><span class="mono">{i:02d}</span><h3>{esc(c["name"])}</h3>'
                   f'<p>{esc(c["blurb"])}</p>' + (f'<span class="n">{n}</span>' if n else '<span class="n soon">Coming soon</span>') + '</a>')
    return '\n      '.join(out)


def sec(title, body, more=''):
    return f'<section style="padding-top:0"><div class="wrap">\n    <div class="sec-head"><h2>{title}</h2>{more}</div>\n    {body}\n  </div></section>'


def empty(text):
    return f'<div class="empty">{text}</div>'


def specs_html(rows):
    return ''.join(f'<div><span class="mono">{esc(k)}</span><b>{esc(v)}</b></div>' for k, v in rows)


SEARCH = ('<label class="search"><svg><use href="#i-search"/></svg>'
          '<input type="search" placeholder="Film, weapon or character…" aria-label="Search films, weapons and characters" autocomplete="off"></label>'
          '<div class="sresults hide" role="listbox"></div>')
def version(rel):
    """A short content hash for assets/{rel}, so browsers drop a cached copy when it changes."""
    return hashlib.sha1((ROOT / 'assets' / rel).read_bytes()).hexdigest()[:8]


NAV = [('films', 'Films'), ('weapons', 'Weapons'), ('characters', 'Characters'), ('categories', 'Categories')]
SUFFIX = ' | Armory.Reel'


